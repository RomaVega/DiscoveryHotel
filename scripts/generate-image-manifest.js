#!/usr/bin/env node
// AUTO-GENERATES lib/image-manifest.ts — a complete list of every image and route
// referenced anywhere in the site, so SitePreloader can background-load the whole
// site without the list ever drifting out of sync.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const IMG_RE = /\/images\/[^"'`)\s]+(?:\s[^"'`)]+)*?\.(?:webp|jpg|jpeg|png|avif)/gi;

function walk(dir, exts, acc) {
  if (!fs.existsSync(dir)) return acc;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === "node_modules" || e.name === ".next") continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, exts, acc);
    else if (exts.some((x) => e.name.endsWith(x))) acc.push(p);
  }
  return acc;
}

// --- Collect image references ---
const sourceFiles = [
  ...walk(path.join(root, "content"), [".json"], []),
  ...walk(path.join(root, "app"), [".tsx", ".ts"], []),
  ...walk(path.join(root, "components"), [".tsx", ".ts"], []),
  ...walk(path.join(root, "lib"), [".tsx", ".ts"], []),
  ...walk(path.join(root, "locales"), [".json"], []),
];

const imgSet = new Set();
for (const f of sourceFiles) {
  if (f.endsWith("image-manifest.ts")) continue; // don't read our own output
  const txt = fs.readFileSync(f, "utf8");
  const matches = txt.match(IMG_RE);
  if (matches) for (const m of matches) imgSet.add(m);
}

// Keep only images that actually exist on disk
const images = [...imgSet]
  .filter((p) => fs.existsSync(path.join(root, "public", p)))
  .sort();

// --- Collect routes from app/**/page.tsx ---
const pageFiles = walk(path.join(root, "app"), ["page.tsx"], []);
const appDir = path.join(root, "app");
const routes = pageFiles
  .map((f) => {
    const rel = path.dirname(f).slice(appDir.length).replace(/\\/g, "/");
    return rel === "" ? "/" : rel;
  })
  .filter((r) => !r.includes("[")) // skip dynamic segments (none expected)
  .sort();

const out = `// AUTO-GENERATED by scripts/generate-image-manifest.js — do not edit by hand.
// Regenerated on every build via the "prebuild" npm script.

export const ALL_IMAGES: readonly string[] = ${JSON.stringify(images, null, 2)};

export const ALL_ROUTES: readonly string[] = ${JSON.stringify(routes, null, 2)};
`;

fs.writeFileSync(path.join(root, "lib", "image-manifest.ts"), out);
console.log(`Wrote ${images.length} images and ${routes.length} routes to lib/image-manifest.ts`);
